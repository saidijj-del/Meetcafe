const Map<String, String> languageNames = {
  "en": "English",
  "ar": "العربية",
  "es": "Español",
  "fr": "Français",
  "zh": "中文",
  "hi": "हिन्दी",
  "pt": "Português",
  "ru": "Русский",
  "de": "Deutsch",
  "ja": "日本語",
};

class LanguageProvider extends ChangeNotifier {
  String _lang = "en";

  String get lang => _lang;
  String get name => languageNames[_lang] ?? _lang;
  bool get isRtl => _lang == "ar";

  String t(String key) =>
      _translations[_lang]?[key] ?? _translations["en"]?[key] ?? key;

  Future<void> init() async {
    final prefs = await SharedPreferences.getInstance();
    final saved = prefs.getString("mc_lang");
    if (saved != null && _translations.containsKey(saved)) {
      _lang = saved;
      notifyListeners();
    }
  }

  Future<void> setLang(String newLang) async {
    if (_translations.containsKey(newLang)) {
      _lang = newLang;
      final prefs = await SharedPreferences.getInstance();
      await prefs.setString("mc_lang", newLang);
      notifyListeners();
    }
  }
}

